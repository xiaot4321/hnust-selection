package cn.hnust.selection.enums;

/**
 * 首期由管理员授权管理接口接受的普通业务能力代码目录。
 *
 * <p>能力代码决定管理员可执行的业务动作，不能把任意客户端字符串直接写进授权表。
 * 普通业务能力均以同一个 ADMIN 角色承载，通过学院/批次授权行限定数据范围；
 * 新能力需要先进入服务端目录并同步 API 契约，避免一次授权接口调用无意创建新权限。</p>
 *
 * <p>{@code ADMIN_ACCOUNT_MANAGER} 不在此枚举中。它是总管理员账号管理能力，只能经初始化或
 * 应急恢复流程维护，永远不能通过普通授予/撤销 API 变更。</p>
 */
public enum AdminCapabilityCode {
    /** 在授权学院范围内维护学生、导师、专业目录和年度资格。 */
    COLLEGE_ADMIN,
    /** 在授权范围内查看批次审计信息。 */
    BATCH_AUDIT
}
